require 'rails_helper'

# Native sources and bytes, no provider calls. This suite has not run here.
RSpec.describe JrcApprovals::DraftReviewCatalog, :approval_core, :authority_core do
  let(:account) { create(:account) }
  let(:actor) { create(:user, account: account, role: :administrator) }
  let(:domain) { authority_domain(account, actor) }
  let(:contract) { domain.fetch(:contract) }
  let(:version) do
    authority_document(domain)
    authority_roster(domain)
    domain[:versions].create!(idempotency_key: SecureRandom.uuid,
      expected_source_digest: domain[:versions].source_digest(contract.id), change_reason: 'Synthetic draft review')
  end

  it 'captures the exact generated version and leaves the signature untouched' do
    version
    before = contract.attributes
    value = JrcApprovals::Catalog.snapshot(account: account, user: actor, key: described_class::KEY, resource_id: contract.id)
    expect(value.dig('values', 'draft_version')).to eq(version.number)
    expect(value.dig('values', 'draft_digest')).to eq(version.source_digest)
    expect(contract.reload.attributes).to eq(before)
  end

  it 'checks actual generated bytes for a decision' do
    version
    expect(described_class.verify(contract, actor)).to be(true)
  end

  it 'requires a version rather than approving an ungenerated draft' do
    domain
    expect { described_class.capture(contract, actor) }.to raise_error(ActiveRecord::RecordNotFound)
  end

  it 'does not reveal the draft from a different account' do
    version
    foreign = create(:user, account: create(:account), role: :administrator)
    expect(described_class.readable?(contract, foreign)).to be(false)
  end

  it 'invalidates the captured draft after a native new version' do
    first = version
    second = domain[:versions].create!(idempotency_key: SecureRandom.uuid,
      expected_source_digest: domain[:versions].source_digest(contract.id), change_reason: 'Synthetic explicit version')
    result = described_class.capture(contract, actor)
    expect(result.dig(:values, :draft_version)).to eq(second.number)
    expect(second.id).not_to eq(first.id)
    expect(first.reload.pdf_sha256).to eq(version.pdf_sha256)
  end
end
