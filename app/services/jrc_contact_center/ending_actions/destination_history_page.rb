# frozen_string_literal: true

# Called only within HistoryContext's current source-authority transaction.
# SQL pagination spans both immutable ledgers without loading an entire history.
class JrcContactCenter::EndingActions::DestinationHistoryPage
  def initialize(account:, member:, origins:, page:)
    @member = member
    @page = page
    @legacy = JrcContactCenter::EndingActionAttempt.where(account: account, origin_id: origins.select(:id))
    @typed = JrcContactCenter::EndingDestinationAttempt.where(account: account, origin_id: origins.select(:id))
  end

  def call
    rows = projected_rows(page_rows)
    total = @legacy.count + @typed.count
    { items: rows, meta: { page: @page, per_page: 20, total: total, pages: (total / 20.0).ceil } }
  end

  private

  def indexed_records(relation, selected, ledger)
    relation.where(id: selected.filter_map { |row| row.id if row.history_ledger == ledger }).includes(outcome: :execution).index_by(&:id)
  end

  def projected_rows(selected)
    legacy = indexed_records(@legacy, selected, 'legacy')
    typed = indexed_records(@typed, selected, 'typed')
    projection = JrcContactCenter::EndingActions::DestinationAttemptProjection.new(member: @member)
    selected.map do |row|
      row.history_ledger == 'legacy' ? projection.legacy(legacy.fetch(row.id)) : projection.call(typed.fetch(row.id))
    end
  end

  def page_rows
    # Both branch queries are generated by native account/source-scoped relations;
    # no SQL fragment, table name or sort is accepted from the HTTP caller.
    legacy = @legacy.select("id, created_at, 'legacy' AS history_ledger").to_sql
    typed = @typed.select("id, created_at, 'typed' AS history_ledger").to_sql
    JrcContactCenter::EndingActionAttempt.unscoped.from("(#{legacy} UNION ALL #{typed}) ending_history")
                                         .select('id, created_at, history_ledger')
                                         .order(Arel.sql('created_at DESC, id DESC, history_ledger ASC'))
                                         .offset((@page - 1) * 20).limit(20).to_a
  end
end
