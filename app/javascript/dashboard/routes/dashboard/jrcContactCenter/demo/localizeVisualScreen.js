export const localizeVisualScreen = (value, t) => {
  if (!t) return value;
  if (typeof value === 'string') return translations[value]?.(t) ?? value;
  if (Array.isArray(value))
    return value.map(item => localizeVisualScreen(item, t));
  if (value && typeof value === 'object')
    return Object.fromEntries(
      Object.entries(value).map(([name, item]) => [
        name,
        localizeVisualScreen(item, t),
      ])
    );
  return value;
};
